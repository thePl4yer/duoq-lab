import fs from 'node:fs/promises';
import path from 'node:path';
import {packageLogger} from './package-logger.mjs';
const root=path.resolve(import.meta.dirname,'..');
const dest=path.join(root,'dist');
await fs.mkdir(dest,{recursive:true});
for(const file of ['index.html','src','data','assets'])await fs.cp(path.join(root,file),path.join(dest,file),{recursive:true});
await fs.mkdir(path.join(dest,'vendor'),{recursive:true});
for(const file of ['rl_replay_subtr_actor.js','rl_replay_subtr_actor_bg.wasm','LICENSE'])await fs.copyFile(path.join(root,'node_modules/@rlrml/subtr-actor',file),path.join(dest,'vendor',file));
await fs.writeFile(path.join(dest,'.nojekyll'),'');
await packageLogger(path.join(dest,'downloads/duoq-logger.zip'));
console.log('Dashboard built: dist/ (including the local WebAssembly parser)');
